def stop_if_files_missing():
    missing = [path.name for path in REQUIRED_FILES if not path.exists()]
    if missing:
        st.error(
            "The app cannot start because these required files are missing from the data folder:\n\n"
            + "\n".join(f"- {name}" for name in missing)
        )
        st.stop()


def normalize_basin_code(series: pd.Series) -> pd.Series:
    """Normalize basin codes so 1 becomes 01 and 21.0 becomes 21."""
    return (
        series.astype(str)
        .str.strip()
        .str.replace(r"\.0$", "", regex=True)
        .str.zfill(2)
    )


def require_columns(df: pd.DataFrame, required: list[str], label: str):
    missing = [column for column in required if column not in df.columns]
    if missing:
        st.error(
            f"{label} is missing expected columns: {', '.join(missing)}. "
            "Please confirm that this file was generated by the revised Objective 1 notebook."
        )
        st.stop()


stop_if_files_missing()


