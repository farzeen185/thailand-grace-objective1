@st.cache_data(show_spinner=False)
def load_data():
    national = pd.read_csv(NATIONAL_FILE)
    basin = pd.read_csv(BASIN_FILE)
    trend = pd.read_csv(TREND_FILE)
    climatology = pd.read_csv(CLIM_FILE)
    seasonal = pd.read_csv(SEASONAL_FILE)
    basin_gdf = gpd.read_file(BASIN_GPKG, engine="pyogrio")

    require_columns(
        national,
        ["month_date", "mean_twsa"],
        NATIONAL_FILE.name,
    )
    require_columns(
        basin,
        ["MB_CODE", "MBASIN_E", "month_date", "twsa_cm"],
        BASIN_FILE.name,
    )
    require_columns(
        trend,
        [
            "MB_CODE",
            "MBASIN_E",
            "sen_slope_cm_per_year",
            "sen_slope_mm_per_year",
            "mann_kendall_p_value",
            "mann_kendall_trend",
        ],
        TREND_FILE.name,
    )
    require_columns(
        climatology,
        [
            "MB_CODE",
            "MBASIN_E",
            "calendar_month",
            "mean_twsa_cm",
        ],
        CLIM_FILE.name,
    )
    require_columns(
        seasonal,
        [
            "MB_CODE",
            "MBASIN_E",
            "highest_storage_month",
            "highest_mean_twsa_cm",
            "lowest_storage_month",
            "lowest_mean_twsa_cm",
            "seasonal_amplitude_cm",
        ],
        SEASONAL_FILE.name,
    )
    require_columns(
        basin_gdf,
        ["MB_CODE", "MBASIN_E", "geometry"],
        BASIN_GPKG.name,
    )

    # Dates
    national["month_date"] = pd.to_datetime(national["month_date"], errors="coerce")
    basin["month_date"] = pd.to_datetime(basin["month_date"], errors="coerce")

    # Basin codes
    for frame in [basin, trend, climatology, seasonal]:
        frame["MB_CODE"] = normalize_basin_code(frame["MB_CODE"])

    basin_gdf["MB_CODE"] = normalize_basin_code(basin_gdf["MB_CODE"])

    # Numeric fields
    national_numeric = [
        "mean_twsa",
        "median_twsa",
        "std_twsa",
        "min_twsa",
        "max_twsa",
        "moving_average_12m",
        "linear_trend",
    ]
    for column in national_numeric:
        if column in national.columns:
            national[column] = pd.to_numeric(national[column], errors="coerce")

    basin_numeric = ["twsa_cm", "moving_average_12m_cm", "valid_pixels"]
    for column in basin_numeric:
        if column in basin.columns:
            basin[column] = pd.to_numeric(basin[column], errors="coerce")

    trend_numeric = [
        "number_of_observations",
        "ols_slope_cm_per_year",
        "ols_slope_mm_per_year",
        "ols_p_value",
        "ols_r_squared",
        "mann_kendall_p_value",
        "mann_kendall_tau",
        "sen_slope_cm_per_year",
        "sen_slope_mm_per_year",
        "sen_lower_cm_per_year",
        "sen_upper_cm_per_year",
    ]
    for column in trend_numeric:
        if column in trend.columns:
            trend[column] = pd.to_numeric(trend[column], errors="coerce")

    clim_numeric = [
        "calendar_month",
        "mean_twsa_cm",
        "median_twsa_cm",
        "standard_deviation_cm",
        "number_of_observations",
    ]
    for column in clim_numeric:
        if column in climatology.columns:
            climatology[column] = pd.to_numeric(climatology[column], errors="coerce")

    seasonal_numeric = [
        "highest_mean_twsa_cm",
        "lowest_mean_twsa_cm",
        "seasonal_amplitude_cm",
    ]
    for column in seasonal_numeric:
        if column in seasonal.columns:
            seasonal[column] = pd.to_numeric(seasonal[column], errors="coerce")

    # Map geometry in geographic coordinates
    if basin_gdf.crs is None:
        st.error("The basin GeoPackage has no CRS information.")
        st.stop()

    basin_gdf = basin_gdf.to_crs("EPSG:4326")

    national = national.sort_values("month_date").reset_index(drop=True)
    basin = basin.sort_values(["MB_CODE", "month_date"]).reset_index(drop=True)
    trend = trend.sort_values("sen_slope_cm_per_year").reset_index(drop=True)
    climatology = climatology.sort_values(["MB_CODE", "calendar_month"]).reset_index(drop=True)

    return national, basin, trend, climatology, seasonal, basin_gdf


national_df, basin_df, trend_df, clim_df, seasonal_df, basin_gdf = load_data()


