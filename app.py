def get_location_series(location_code: str) -> pd.DataFrame:
    if location_code == "NATIONAL":
        frame = national_df.copy()
        frame = frame.rename(
            columns={
                "mean_twsa": "twsa_cm",
                "moving_average_12m": "moving_average_12m_cm",
            }
        )
        return frame.sort_values("month_date")

    return (
        basin_df.loc[basin_df["MB_CODE"] == location_code]
        .copy()
        .sort_values("month_date")
    )


def calculate_series_statistics(series: pd.DataFrame):
    observed = (
        series.dropna(subset=["month_date", "twsa_cm"])
        .sort_values("month_date")
        .copy()
    )

    if len(observed) < 3:
        return None

    elapsed_years = (
        observed["month_date"] - observed["month_date"].min()
    ).dt.days / 365.2425

    ols = linregress(elapsed_years, observed["twsa_cm"])
    sen = theilslopes(observed["twsa_cm"], elapsed_years, alpha=0.95)

    monthly_climatology = (
        observed.assign(calendar_month=observed["month_date"].dt.month)
        .groupby("calendar_month")["twsa_cm"]
        .mean()
    )

    minimum_row = observed.loc[observed["twsa_cm"].idxmin()]
    maximum_row = observed.loc[observed["twsa_cm"].idxmax()]

    return {
        "observations": int(len(observed)),
        "missing_months": int(series["twsa_cm"].isna().sum()),
        "mean": float(observed["twsa_cm"].mean()),
        "minimum": float(minimum_row["twsa_cm"]),
        "minimum_date": minimum_row["month_date"],
        "maximum": float(maximum_row["twsa_cm"]),
        "maximum_date": maximum_row["month_date"],
        "ols_slope": float(ols.slope),
        "ols_p_value": float(ols.pvalue),
        "ols_r_squared": float(ols.rvalue ** 2),
        "sen_slope": float(sen.slope),
        "sen_lower": float(sen.low_slope),
        "sen_upper": float(sen.high_slope),
        "seasonal_amplitude": float(monthly_climatology.max() - monthly_climatology.min()),
    }


def make_time_series_figure(series: pd.DataFrame, title: str):
    figure = go.Figure()

    figure.add_trace(
        go.Scatter(
            x=series["month_date"],
            y=series["twsa_cm"],
            mode="lines+markers",
            name="Monthly TWSA",
            connectgaps=False,
            marker={"size": 4},
        )
    )

    if "moving_average_12m_cm" in series.columns:
        figure.add_trace(
            go.Scatter(
                x=series["month_date"],
                y=series["moving_average_12m_cm"],
                mode="lines",
                name="12-month moving average",
                connectgaps=False,
            )
        )

    # National CSV already contains the preliminary OLS line produced by the notebook.
    if "linear_trend" in series.columns and series["linear_trend"].notna().any():
        figure.add_trace(
            go.Scatter(
                x=series["month_date"],
                y=series["linear_trend"],
                mode="lines",
                name="Linear trend",
                connectgaps=False,
                line={"dash": "dash"},
            )
        )

    figure.add_hline(y=0, line_dash="dash")
    figure.update_layout(
        title=title,
        xaxis_title="Date",
        yaxis_title="TWSA (cm)",
        height=520,
        hovermode="x unified",
        legend_title_text="",
    )

    return figure


def csv_bytes(frame: pd.DataFrame) -> bytes:
    return frame.to_csv(index=False).encode("utf-8")


